import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { mediaApi } from '../../api/media';
import { Card, CardHeader, CardTitle, CardContent } from '../../components/ui/Card';
import { Button } from '../../components/ui/Button';
import { Modal } from '../../components/ui/Modal';
import { CopyButton, EmptyState } from '../../components/shared/EmptyState';
import {
  Image as ImageIcon,
  ExternalLink,
  BookOpen,
  Calendar,
  Sparkles,
  Maximize2,
} from 'lucide-react';
import { MediaAsset } from '../../api/types';

interface MediaGalleryProps {
  generationId?: string;
  images?: any[];
}

export const MediaGallery: React.FC<MediaGalleryProps> = ({ generationId, images: propImages }) => {
  const navigate = useNavigate();
  const [selectedAsset, setSelectedAsset] = useState<any | null>(null);

  // If images are passed as props (e.g. from blog view), use those, otherwise query media API
  const { data: mediaAssets, isLoading } = useQuery({
    queryKey: ['media', generationId],
    queryFn: () => mediaApi.list(generationId),
    enabled: !propImages,
  });

  const displayImages = propImages || mediaAssets || [];

  return (
    <div className="space-y-6">
      {isLoading ? (
        <div className="p-12 text-center text-xs text-text-muted">Loading media assets...</div>
      ) : displayImages.length === 0 ? (
        <EmptyState
          icon={<ImageIcon className="w-8 h-8 text-text-muted" />}
          title="No diagrams or images found"
          description="Diagrams generated by Gemini and stored in Cloudinary will appear here."
        />
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-5">
          {displayImages.map((asset, idx) => {
            const url = asset.cloudinary_url || asset.url;
            return (
              <Card
                key={asset.id || idx}
                className="glass-card hover:border-cyan-500/40 transition-all overflow-hidden flex flex-col justify-between group"
              >
                <div
                  onClick={() => setSelectedAsset(asset)}
                  className="relative aspect-video bg-surface-muted cursor-pointer overflow-hidden flex items-center justify-center"
                >
                  {url ? (
                    <img
                      src={url}
                      alt={asset.alt_text || asset.alt || 'Generated figure'}
                      className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300"
                      loading="lazy"
                    />
                  ) : (
                    <ImageIcon className="w-8 h-8 text-text-muted" />
                  )}
                  <div className="absolute inset-0 bg-black/40 opacity-0 group-hover:opacity-100 transition-opacity flex items-center justify-center">
                    <span className="p-2 rounded-full bg-black/60 text-white">
                      <Maximize2 className="w-4 h-4" />
                    </span>
                  </div>
                </div>

                <CardContent className="p-4 space-y-2 flex-1">
                  <div className="flex items-center justify-between">
                    <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-surface-elevated text-cyan-400">
                      {asset.placeholder || 'Figure'}
                    </span>
                    <span className="text-[11px] text-text-muted truncate">
                      {asset.filename}
                    </span>
                  </div>
                  <p className="text-xs font-semibold text-text-primary line-clamp-1">
                    {asset.alt_text || asset.alt || 'Technical Architecture'}
                  </p>
                  {(asset.caption || asset.prompt) && (
                    <p className="text-[11px] text-text-secondary line-clamp-2 italic">
                      "{asset.caption || asset.prompt}"
                    </p>
                  )}
                </CardContent>

                <div className="p-3 bg-surface-muted/40 border-t border-border/40 flex items-center justify-between text-xs">
                  {url && <CopyButton text={url} label="Copy Link" className="text-[11px] py-1 px-2.5 h-7" />}
                  {asset.generation_id && (
                    <Button
                      variant="ghost"
                      size="sm"
                      onClick={() => navigate(`/blogs/${asset.generation_id}`)}
                      className="text-[11px] text-text-secondary hover:text-cyan-400 h-7"
                    >
                      View Blog
                    </Button>
                  )}
                </div>
              </Card>
            );
          })}
        </div>
      )}

      {/* Full Preview Modal */}
      {selectedAsset && (
        <Modal
          isOpen={Boolean(selectedAsset)}
          onClose={() => setSelectedAsset(null)}
          title={selectedAsset.alt_text || selectedAsset.alt || 'Image Preview'}
          description={selectedAsset.caption || selectedAsset.filename}
          maxWidth="xl"
        >
          <div className="space-y-4">
            <div className="rounded-xl overflow-hidden border border-border/60 bg-black/40 flex items-center justify-center">
              <img
                src={selectedAsset.cloudinary_url || selectedAsset.url}
                alt={selectedAsset.alt_text || selectedAsset.alt}
                className="max-h-[500px] w-auto object-contain mx-auto"
              />
            </div>
            {selectedAsset.prompt && (
              <div className="p-3.5 rounded-lg bg-surface-elevated text-xs space-y-1">
                <span className="font-semibold text-text-muted uppercase text-[10px] font-mono">Generation Prompt:</span>
                <p className="text-text-secondary leading-relaxed font-mono text-[11px]">
                  {selectedAsset.prompt}
                </p>
              </div>
            )}
            <div className="flex items-center justify-between pt-2">
              <span className="text-xs text-text-muted font-mono truncate max-w-sm">
                {selectedAsset.cloudinary_url || selectedAsset.url}
              </span>
              <CopyButton text={selectedAsset.cloudinary_url || selectedAsset.url} label="Copy Image URL" />
            </div>
          </div>
        </Modal>
      )}
    </div>
  );
};
